// Builds scripts/data/real/cpi.js from tools/data/cpi-u-nsa.tsv.
//
//   node tools/build-cpi.js
//
// Source: BLS CPI-U, U.S. city average, all items, not seasonally adjusted (series CUUR0000SA0, 1982-84=100).
// Output: CPI_QUARTERLY — the average of each calendar quarter's published months, keyed "YYYY-Qn".
// Months BLS did not publish (October 2025, lost to the 2025 lapse in appropriations) are left out
// of the average rather than estimated. Quarters with no published months are omitted.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SRC = path.join(__dirname, "data", "cpi-u-nsa.tsv");
const OUT = path.join(ROOT, "scripts", "data", "real", "cpi.js");

// Published BLS annual averages, used to check the monthly data was transcribed correctly
const KNOWN_ANNUAL = { 1950: 24.1, 1960: 29.6, 1970: 38.8, 1980: 82.4, 1990: 130.7, 2000: 172.2, 2010: 218.056, 2020: 258.811, 2024: 313.689 };

const monthly = {};
for (const line of fs.readFileSync(SRC, "utf8").split(/\r?\n/)) {
  if (!/^\d{4}\t/.test(line)) continue;
  const cells = line.split("\t");
  const year = Number(cells[0]);
  monthly[year] = cells.slice(1, 13).map((c) => {
    const v = Number(c.trim());
    return c.trim() && Number.isFinite(v) ? v : null;
  });
}

const avg = (vals) => vals.reduce((n, v) => n + v, 0) / vals.length;
const quarterly = {};
const gaps = [];
for (const [year, months] of Object.entries(monthly)) {
  for (let q = 0; q < 4; q++) {
    const slice = months.slice(q * 3, q * 3 + 3);
    const published = slice.filter((v) => v !== null);
    if (published.length === 0) continue;
    if (published.length < 3) gaps.push(`${year}-Q${q + 1} (${published.length}/3 months)`);
    quarterly[`${year}-Q${q + 1}`] = Math.round(avg(published) * 1000) / 1000;
  }
}

// --- verify against published annual averages ----------------------------------------------
let ok = true;
for (const [year, expected] of Object.entries(KNOWN_ANNUAL)) {
  const months = monthly[year];
  if (!months || months.some((v) => v === null)) { console.error(`missing data for ${year}`); ok = false; continue; }
  const decimals = Number(year) >= 2007 ? 3 : 1;
  const got = Number(avg(months).toFixed(decimals));
  const match = Math.abs(got - expected) < 1e-9;
  console.log(`${year} annual avg ${got.toFixed(decimals)} vs BLS ${expected} ${match ? "OK" : "MISMATCH"}`);
  if (!match) ok = false;
}
if (!ok) { console.error("Annual averages don't match BLS — check the TSV."); process.exit(1); }

const keys = Object.keys(quarterly);
const header = `// GENERATED by tools/build-cpi.js — do not edit by hand.
// CPI-U, U.S. city average, all items, not seasonally adjusted (BLS series CUUR0000SA0, 1982-84=100).
// Quarterly values are the average of that quarter's published months (${keys[0]} … ${keys[keys.length - 1]}).
// Partial quarters: ${gaps.length ? gaps.join(", ") : "none"}.
`;
const body = `const CPI_QUARTERLY = ${JSON.stringify(quarterly).replace(/,"/g, ',\n  "').replace("{", "{\n  ").replace(/}$/, "\n}")};
const CPI_FIRST = "${keys[0]}";
const CPI_LAST = "${keys[keys.length - 1]}";
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + body);
console.log(`Wrote ${keys.length} quarters (${keys[0]} … ${keys[keys.length - 1]}) to ${path.relative(ROOT, OUT)}`);
if (gaps.length) console.log(`Partial quarters: ${gaps.join(", ")}`);
